"""Assemble nb/*.py (+ nb/embed/**) into kaggle/casmi26-ours.ipynb and kaggle/kernel-metadata.json.

usage: python tools/build_notebook.py [--config configs/v2-0.404.json] [--user KAGGLE_USERNAME] [--slug casmi26-ours]
                                      [--title T] [--out DIR]
                                      [--no-pin] [--set KEY=VALUE ...]
  --out writes the notebook + kernel-metadata.json elsewhere (e.g. a git-ignored scratch dir for a one-off push)
  --no-pin uses Kaggle's latest image instead of the reference notebook's pinned docker image
  --config applies a named CFG preset (JSON) from configs/; --set (applied after it) overrides single keys
  --set overrides CFG defaults in the built notebook only (values parsed as JSON, e.g. --set ICE_LAM=0.8 --set USE_GL=false)
The Kaggle username defaults to $KAGGLE_USERNAME, then to the "username" field of ~/.kaggle/kaggle.json.
"""
import argparse, glob, json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NB, OUT = os.path.join(ROOT, 'nb'), os.path.join(ROOT, 'kaggle')

COMPETITION = 'enveda-CASMI26-molecule-id-mass-spectra'
DATASETS = [   # the reference notebook's inputs, in its order
    'prvsiyan/casmi26-fp-models-v2', 'prvsiyan/casmi26-ranker-features', 'megayak/casmi26-simulated-ranker-rows',
    'ahmedberatozer/casmi26-fpnet-full1', 'ahmedberatozer/casmi26-glacier', 'ahmedberatozer/casmi26-iceberg',
    'ahmedberatozer/casmi26-pubchem-tier', 'ahmedberatozer/casmi26-v2-pool', 'ahmedberatozer/casmi26-v3-models',
    'ahmedberatozer/casmi26-v4b-models', 'sergiomalv/casmi-chebi-lmsd-structures', 'prvsiyan/coconut-casmi26-candidates',
    'metric/rdkit-2026-3-3-wheel',
    'dmitriigluzdov/casmi26-pubchem-popularity-prior',   # POP_MU (off by default)
    'dmitriigluzdov/casmi26-fold-safe-fpnet',            # validation only: FP_BANK='fold0', VAL_SET='fold0_np'
]
OUR_RANKER = '{user}/casmi26-ours-ranker'                # our own private dataset; attached only when RANKER needs it
# the reference notebook's pinned environment (Python 3.12: the ICEBERG/GLACIER wheels are cp312)
DOCKER_IMAGE = ('gcr.io/kaggle-private-byod/python@sha256:'
                '37c64f7dd9c54116ecd1bcc88817c5469b88387388fade02bfa8bf3fc647d461')


def kaggle_user():
    if os.environ.get('KAGGLE_USERNAME'):
        return os.environ['KAGGLE_USERNAME']
    p = os.path.join(os.path.expanduser('~'), '.kaggle', 'kaggle.json')
    if os.path.exists(p):
        return json.load(open(p)).get('username')      # only the username is read
    return None


E006_NB = os.path.join(ROOT, 'reference', 'e006', 'casmi26-e006-window-40-ice-fallback-true.ipynb')


def e006_embed():
    """E006_FUSE: the code cells of the public notebook snapshot (reference/e006/, Apache-2.0), unchanged, as one JSON list, plus its notice.
    nb/embed/e006_stage.py turns them into a script at run time. Embedded only when the option is on."""
    nb = json.load(open(E006_NB, encoding='utf-8'))
    cells = [''.join(c['source']) for c in nb['cells'] if c['cell_type'] == 'code']
    notice = open(os.path.join(os.path.dirname(E006_NB), 'NOTICE.md'), encoding='utf-8').read()
    return {'e006/cells.json': json.dumps(cells), 'e006/NOTICE.md': notice}


def code_cell(src, cid):
    lines = src.rstrip('\n').split('\n')
    return dict(cell_type='code', id=cid, execution_count=None, metadata={}, outputs=[],
                source=[l + '\n' for l in lines[:-1]] + [lines[-1]])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--user'); ap.add_argument('--slug', default='casmi26-ours'); ap.add_argument('--title')
    ap.add_argument('--set', action='append', default=[]); ap.add_argument('--config')
    ap.add_argument('--out', default=OUT); ap.add_argument('--no-pin', action='store_true')
    a = ap.parse_args()

    embed = {}
    for p in sorted(glob.glob(os.path.join(NB, 'embed', '**', '*.py'), recursive=True)):
        embed[os.path.relpath(p, os.path.join(NB, 'embed')).replace(os.sep, '/')] = open(p, encoding='utf-8').read()
    over_all = {}
    cells = [code_cell('# embedded sources (generated by tools/build_notebook.py from nb/embed/ -- edit there)\nEMBED = '
                       + repr(embed), 'embed')]
    for p in sorted(glob.glob(os.path.join(NB, '[0-9][0-9]_*.py'))):
        src = open(p, encoding='utf-8').read()
        if os.path.basename(p).startswith('00_') and (a.set or a.config):
            over = json.load(open(a.config, encoding='utf-8')) if a.config else {}
            for kv in a.set:
                k, v = kv.split('=', 1)
                over[k] = json.loads(v)
            src += f'\nCFG.update({over!r})   # --set overrides from build_notebook.py\n'
            over_all = over
        cells.append(code_cell(src, os.path.basename(p)[:-3].replace('_', '-')))
    if over_all.get('E006_BASE'):                             # "e006 improved": two extra cells (after the base lists, at the end)
        assert not over_all.get('E006_FUSE'), 'E006_BASE and E006_FUSE are two different designs'
        ids = [c['id'] for c in cells]
        cells.insert(ids.index('06-base-lists') + 1, code_cell(open(os.path.join(NB, 'e006imp_stage.py'), encoding='utf-8').read(), 'e006imp-stage'))
        cells.append(code_cell(open(os.path.join(NB, 'e006imp_final.py'), encoding='utf-8').read(), 'e006imp-final'))
    if over_all.get('E006_FUSE') or over_all.get('E006_BASE'):   # the public notebook's cells ride along (nb/09_e006.py, nb/e006imp_stage.py)
        embed.update(e006_embed())
        cells[0] = code_cell('# embedded sources (generated by tools/build_notebook.py from nb/embed/ -- edit there)\nEMBED = '
                             + repr(embed), 'embed')
    nb = dict(cells=cells, metadata=dict(kernelspec=dict(display_name='Python 3', language='python', name='python3'),
                                         language_info=dict(name='python')), nbformat=4, nbformat_minor=5)
    out = a.out
    os.makedirs(out, exist_ok=True)
    code_file = f'{a.slug}.ipynb'
    json.dump(nb, open(os.path.join(out, code_file), 'w', encoding='utf-8'), indent=1)

    user = a.user or kaggle_user()
    datasets = list(DATASETS)
    if over_all.get('RANKER') in ('ours', 'blend'):
        datasets.append(OUR_RANKER.format(user=user or 'YOUR_KAGGLE_USERNAME'))
    if over_all.get('RANKER') in ('fs', 'fs_avg'):          # the ranker fitted to the fold-safe FPNet's features (private dataset)
        datasets.append((user or 'YOUR_KAGGLE_USERNAME') + '/' + (over_all.get('RANKER_FS_DS') or 'casmi26-ours-ranker-fs'))
    if over_all.get('RANKER') in ('fs', 'fs_avg') and over_all.get('RANKER_FS_NET'):     # our own fold-safe network (private dataset)
        datasets.append((user or 'YOUR_KAGGLE_USERNAME') + '/' + str(over_all['RANKER_FS_NET']).split('/')[0])
    if over_all.get('PC_MODELS') == 'hn':
        datasets.append((user or 'YOUR_KAGGLE_USERNAME') + '/casmi26-fpnet-pc-hn')
    if over_all.get('ADD_JOIN_MU'):                         # models of the adduct-evidence term (private dataset, nb/embed/adduct_prior.py)
        datasets.append((user or 'YOUR_KAGGLE_USERNAME') + '/casmi26-ours-adduct-prior')
    if over_all.get('POP_SPLIT'):                           # substance / spectral-library deposit counts (our dataset, nb/embed/pop_split.py)
        datasets.append((user or 'YOUR_KAGGLE_USERNAME') + '/casmi26-pop-split')
    if over_all.get('ICE_FT'):
        datasets.append('ahmedberatozer/casmi26-ice-ft')
    if over_all.get('ENG_EXTRA_FPNET'):
        v = str(over_all['ENG_EXTRA_FPNET'])                # 'np-ours' = our own fine-tune (train/train_eng_fpnet.py), else 'owner/slug'
        datasets.append((user or 'YOUR_KAGGLE_USERNAME') + '/casmi26-fp-np-ours' if v == 'np-ours' else v)   # huseyinemreaksoy/casmi26-fp-np-ours
    meta = dict(id=f'{user or "YOUR_KAGGLE_USERNAME"}/{a.slug}', title=a.title or a.slug, code_file=code_file,
                language='python', kernel_type='notebook', is_private=True, enable_gpu=True, enable_tpu=False,
                enable_internet=False, machine_shape='NvidiaTeslaT4', dataset_sources=datasets,
                competition_sources=[COMPETITION], kernel_sources=[], model_sources=[])
    if not a.no_pin:
        meta['docker_image'] = DOCKER_IMAGE
    json.dump(meta, open(os.path.join(out, 'kernel-metadata.json'), 'w'), indent=1)
    n = sum(len(c['source']) for c in cells)
    print(f'wrote {os.path.relpath(os.path.join(out, code_file))} ({len(cells)} cells, {n} lines, {len(embed)} embedded files) + kernel-metadata.json '
          f'(id {meta["id"]})')
    if not user:
        print('WARNING: Kaggle username unknown -> set KAGGLE_USERNAME or pass --user before `kaggle kernels push`')


if __name__ == '__main__':
    main()
